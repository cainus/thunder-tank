// Generates the low-poly tank models (Wavefront .obj + .mtl) that the in-game 3D
// renderer loads for the tanks and their turrets. Like the tree generator, the
// geometry lives in a small deterministic script so we can regenerate/tweak the
// models without committing opaque binary assets. Run with
// `node scripts/generate-tank-model.mjs`.
//
// Both models are authored in the same unit space as the tree model: y is up,
// the tank's footprint sits on the ground plane (y = 0), and forward is -Z so a
// zero yaw points "up-screen" once the renderer maps world Z -> screen Y. The
// hull and turret are separate models because the turret rotates independently;
// the turret is authored already sitting on top of the hull so both can be
// placed at the same ground position and scaled uniformly.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../public/assets/models");

// A model builder that accumulates vertices and faces grouped by material name.
function createModel() {
  const positions = [];
  const faces = []; // { verts: number[], group }

  function addVertex(x, y, z) {
    positions.push([x, y, z]);
    return positions.length; // .obj indices are 1-based
  }

  // Axis-aligned box spanning [min, max] on each axis. Wound so every quad's
  // outward face points away from the box centre (correct front faces for the
  // single-sided default material).
  function addBox(min, max, group) {
    const [x0, y0, z0] = min;
    const [x1, y1, z1] = max;
    const v = [
      addVertex(x0, y0, z0), // 0
      addVertex(x1, y0, z0), // 1
      addVertex(x1, y0, z1), // 2
      addVertex(x0, y0, z1), // 3
      addVertex(x0, y1, z0), // 4
      addVertex(x1, y1, z0), // 5
      addVertex(x1, y1, z1), // 6
      addVertex(x0, y1, z1), // 7
    ];
    const quad = (a, b, c, d) => {
      faces.push({ verts: [v[a], v[b], v[c]], group });
      faces.push({ verts: [v[a], v[c], v[d]], group });
    };
    quad(4, 5, 6, 7); // top (+y)
    quad(3, 2, 1, 0); // bottom (-y)
    quad(0, 1, 5, 4); // front (-z)
    quad(2, 3, 7, 6); // back (+z)
    quad(3, 0, 4, 7); // left (-x)
    quad(1, 2, 6, 5); // right (+x)
  }

  return { positions, faces, addBox };
}

function serialize(model, name, materials) {
  const objLines = [
    `# Thunder Tank low-poly ${name}`,
    "# Generated by scripts/generate-tank-model.mjs — do not edit by hand.",
    `mtllib ${name}.mtl`,
    `o ${name}`,
  ];

  for (const [x, y, z] of model.positions) {
    objLines.push(`v ${x.toFixed(5)} ${y.toFixed(5)} ${z.toFixed(5)}`);
  }

  let currentGroup = "";
  for (const face of model.faces) {
    if (face.group !== currentGroup) {
      objLines.push(`usemtl ${face.group}`);
      currentGroup = face.group;
    }
    objLines.push(`f ${face.verts.join(" ")}`);
  }

  const mtlLines = [`# Thunder Tank low-poly ${name} materials`, "# Generated by scripts/generate-tank-model.mjs — do not edit by hand."];
  for (const material of materials) {
    mtlLines.push(
      "",
      `newmtl ${material.name}`,
      `Kd ${material.kd.join(" ")}`,
      `Ka ${material.ka.join(" ")}`,
      `Ks ${material.ks.join(" ")}`,
      `Ns ${material.ns.toFixed(1)}`,
    );
  }

  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, `${name}.obj`), `${objLines.join("\n")}\n`);
  writeFileSync(resolve(outDir, `${name}.mtl`), `${mtlLines.join("\n")}\n`);
  return model.positions.length;
}

// --- Hull -------------------------------------------------------------------
// The "hull" material is recoloured per team at runtime by the renderer, so it
// is authored a mid grey; the treads stay a fixed dark colour for contrast.
function buildHull() {
  const model = createModel();
  // Lower chassis.
  model.addBox([-0.5, 0.1, -0.85], [0.5, 0.42, 0.85], "hull");
  // Raised upper deck (slightly shorter so the silhouette reads as a tank).
  model.addBox([-0.42, 0.42, -0.68], [0.42, 0.52, 0.6], "hull");
  // Left and right tread runs, flanking the chassis and reaching a touch
  // further fore/aft so treads frame the body.
  model.addBox([-0.64, 0.0, -0.92], [-0.42, 0.34, 0.92], "tread");
  model.addBox([0.42, 0.0, -0.92], [0.64, 0.34, 0.92], "tread");
  return model;
}

// --- Turret -----------------------------------------------------------------
// Sits on top of the hull deck (y >= 0.52) so hull + turret share a ground
// origin. The barrel points forward along -Z.
function buildTurret() {
  const model = createModel();
  // Turret box / mantlet.
  model.addBox([-0.34, 0.52, -0.34], [0.34, 0.82, 0.3], "turret");
  // Gun barrel, extending forward past the turret front.
  model.addBox([-0.08, 0.6, -1.18], [0.08, 0.74, -0.3], "turret");
  return model;
}

const hullMaterials = [
  // Recoloured per team at runtime (see tank-3d.ts); grey is the neutral base.
  { name: "hull", kd: [0.55, 0.57, 0.55], ka: [0.14, 0.15, 0.14], ks: [0.05, 0.05, 0.05], ns: 12.0 },
  { name: "tread", kd: [0.16, 0.16, 0.17], ka: [0.04, 0.04, 0.04], ks: [0.02, 0.02, 0.02], ns: 6.0 },
];

const turretMaterials = [
  { name: "turret", kd: [0.34, 0.35, 0.34], ka: [0.09, 0.09, 0.09], ks: [0.06, 0.06, 0.06], ns: 14.0 },
];

const hullVerts = serialize(buildHull(), "tank-hull", hullMaterials);
const turretVerts = serialize(buildTurret(), "tank-turret", turretMaterials);

console.log(`Wrote tank-hull (${hullVerts} verts) and tank-turret (${turretVerts} verts) to ${outDir}`);
