// Generates the low-poly parked-car model (Wavefront .obj + .mtl) that the
// in-game 3D renderer loads for the parked cars that line the urban road. Mirrors
// the crate generator (scripts/generate-crate-model.mjs): keeping the geometry in
// a small, deterministic generator lets us regenerate/tweak the model without
// committing an opaque binary asset. Run with `node scripts/generate-car-model.mjs`.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../public/assets/models");

// The car is authored around a 1-unit "length": it sits on the ground plane
// (y = 0), is centred on the origin, and spans a 1-unit footprint along +X (its
// length) so the renderer can scale it to any world size uniformly (see
// CAR_WORLD_SCALE). Width (Z) is a little under half the length, echoing the
// 64x30 flat sprite the model replaces.
const positions = [];
// Each face records the triangle's vertex indices, the material, and the parent
// object. The body is split into its own object so the 3D overlay can recolour
// just the painted panels per parked car (see CarOverlay3D.tintBody).
const faces = [];

function addVertex(x, y, z) {
  positions.push([x, y, z]);
  return positions.length; // .obj indices are 1-based
}

// Emits a quad as two triangles. Corners must be given counter-clockwise as seen
// from outside the face so computeVertexNormals() (run by the loader) points the
// normal outward.
function addQuad(a, b, c, d, material, object) {
  const ia = addVertex(...a);
  const ib = addVertex(...b);
  const ic = addVertex(...c);
  const id = addVertex(...d);
  faces.push({ verts: [ia, ib, ic], material, object });
  faces.push({ verts: [ia, ic, id], material, object });
}

// Adds an axis-aligned box spanning [min, max] on each axis, with every face
// wound CCW as seen from outside so its normal points away from the box centre.
function addBox(min, max, material, object) {
  const [x0, y0, z0] = min;
  const [x1, y1, z1] = max;

  // +X and -X
  addQuad([x1, y0, z1], [x1, y0, z0], [x1, y1, z0], [x1, y1, z1], material, object);
  addQuad([x0, y0, z0], [x0, y0, z1], [x0, y1, z1], [x0, y1, z0], material, object);
  // +Z and -Z
  addQuad([x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1], material, object);
  addQuad([x1, y0, z0], [x0, y0, z0], [x0, y1, z0], [x1, y1, z0], material, object);
  // +Y (top) and -Y (underside)
  addQuad([x0, y1, z1], [x1, y1, z1], [x1, y1, z0], [x0, y1, z0], material, object);
  addQuad([x0, y0, z0], [x1, y0, z0], [x1, y0, z1], [x0, y0, z1], material, object);
}

// Painted lower body (the recolourable hull). Sits just above the ground so the
// wheels peek below it.
addBox([-0.5, 0.06, -0.2], [0.5, 0.3, 0.2], "carBody", "CarBody");

// Greenhouse / cabin in tinted glass, inset from the body and raised on top so
// the car reads as a cabin-over-hull silhouette from the tilted top-down camera.
addBox([-0.16, 0.3, -0.16], [0.26, 0.46, 0.16], "carGlass", "CarCabin");

// Four dark wheels at the corners, poking a little past the body sides.
const wheelHalfLength = 0.09; // along X
const wheelHalfWidth = 0.05; // along Z
const wheelTop = 0.12;
const wheelX = 0.32; // distance of each axle from centre
const wheelZ = 0.21; // slightly outside the 0.2 body half-width
for (const sx of [-1, 1]) {
  for (const sz of [-1, 1]) {
    const cx = sx * wheelX;
    const cz = sz * wheelZ;
    addBox(
      [cx - wheelHalfLength, 0, cz - wheelHalfWidth],
      [cx + wheelHalfLength, wheelTop, cz + wheelHalfWidth],
      "carTrim",
      "CarWheels",
    );
  }
}

const objLines = [
  "# Thunder Tank low-poly parked car obstacle",
  "# Generated by scripts/generate-car-model.mjs — do not edit by hand.",
  "mtllib car.mtl",
];

for (const [x, y, z] of positions) {
  objLines.push(`v ${x.toFixed(5)} ${y.toFixed(5)} ${z.toFixed(5)}`);
}

// Emit faces grouped by object so OBJLoader creates one child mesh per object,
// which lets the overlay find and recolour the CarBody mesh independently.
let currentObject = "";
let currentMaterial = "";
for (const face of faces) {
  if (face.object !== currentObject) {
    objLines.push(`o ${face.object}`);
    currentObject = face.object;
    currentMaterial = "";
  }
  if (face.material !== currentMaterial) {
    objLines.push(`usemtl ${face.material}`);
    currentMaterial = face.material;
  }
  objLines.push(`f ${face.verts.join(" ")}`);
}

const mtlLines = [
  "# Thunder Tank low-poly parked car materials",
  "# Generated by scripts/generate-car-model.mjs — do not edit by hand.",
  // The body colour is a neutral base; the overlay clones and recolours this
  // material per parked car so the row of cars stays visually varied.
  "newmtl carBody",
  "Kd 0.72 0.24 0.20",
  "Ka 0.14 0.05 0.04",
  "Ks 0.28 0.28 0.30",
  "Ns 32.0",
  "",
  // Tinted, slightly reflective glass for the cabin/greenhouse.
  "newmtl carGlass",
  "Kd 0.16 0.22 0.30",
  "Ka 0.04 0.06 0.08",
  "Ks 0.40 0.44 0.50",
  "Ns 48.0",
  "",
  // Dark rubber/trim for the wheels.
  "newmtl carTrim",
  "Kd 0.08 0.08 0.09",
  "Ka 0.02 0.02 0.02",
  "Ks 0.05 0.05 0.05",
  "Ns 8.0",
];

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "car.obj"), `${objLines.join("\n")}\n`);
writeFileSync(resolve(outDir, "car.mtl"), `${mtlLines.join("\n")}\n`);

console.log(`Wrote ${positions.length} vertices / ${faces.length} faces to ${outDir}`);
