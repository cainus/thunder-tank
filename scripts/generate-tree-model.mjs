// Generates the low-poly tree model (Wavefront .obj + .mtl) that the in-game 3D
// renderer loads for urban trees. Keeping the geometry in a small, deterministic
// generator lets us regenerate/tweak the model without committing an opaque
// binary asset. Run with `node scripts/generate-tree-model.mjs`.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../public/assets/models");

// The model is authored around a 1-unit "footprint": the trunk stands at the
// origin on the ground plane (y = 0) and the renderer scales it to any world
// size uniformly.
//
// Trunk visibility: the in-game camera views trees at an oblique tilt (see
// TREE_CAMERA_TILT in urban-decor.ts) so the canopy leans up-screen and exposes
// the trunk below it. For the trunk to actually show, the canopy must sit high
// enough above the ground that its leaned lower edge clears the trunk base —
// i.e. canopyBaseHeight * sin(tilt) must exceed the canopy base radius. The tall
// trunk / lifted canopy below satisfy that (previously the canopy sat almost on
// the ground and overhung the trunk from every angle, so trees rendered as bare
// blobs with no visible trunk).
const TRUNK_RADIUS = 0.2;
const TRUNK_HEIGHT = 2.3;
const TRUNK_SEGMENTS = 6;
// Two stacked canopy cones give a layered, low-poly conifer silhouette. The
// lowest canopy base sits just under the trunk top so the foliage wraps the
// trunk without burying it.
const CANOPY_SEGMENTS = 8;
const CANOPY_TIERS = [
  { baseY: 2.2, radius: 0.95, height: 1.4 },
  { baseY: 2.95, radius: 0.68, height: 1.35 },
];

const positions = [];
const faces = []; // { verts: [i, j, k], group }

function addVertex(x, y, z) {
  positions.push([x, y, z]);
  return positions.length; // .obj indices are 1-based
}

function buildTrunk() {
  const bottom = [];
  const top = [];

  for (let s = 0; s < TRUNK_SEGMENTS; s += 1) {
    const angle = (s / TRUNK_SEGMENTS) * Math.PI * 2;
    const x = Math.cos(angle) * TRUNK_RADIUS;
    const z = Math.sin(angle) * TRUNK_RADIUS;
    bottom.push(addVertex(x, 0, z));
    top.push(addVertex(x, TRUNK_HEIGHT, z));
  }

  for (let s = 0; s < TRUNK_SEGMENTS; s += 1) {
    const next = (s + 1) % TRUNK_SEGMENTS;
    // Wind each side quad counter-clockwise as seen from OUTSIDE the trunk so the
    // face normal points radially outward. The reversed winding used before made
    // the trunk's outward faces back-faces, which three.js culls by default
    // (Material.side === FrontSide) — the trunk vanished and trees rendered as
    // canopy-only blobs (the "trees have no trunks" defect). The canopy cones are
    // already wound outward, which is why only the trunk disappeared.
    faces.push({ verts: [bottom[s], top[next], bottom[next]], group: "trunk" });
    faces.push({ verts: [bottom[s], top[s], top[next]], group: "trunk" });
  }
}

function buildCanopyTier(baseY, radius, height) {
  const apex = addVertex(0, baseY + height, 0);
  const ring = [];

  for (let s = 0; s < CANOPY_SEGMENTS; s += 1) {
    const angle = (s / CANOPY_SEGMENTS) * Math.PI * 2;
    ring.push(addVertex(Math.cos(angle) * radius, baseY, Math.sin(angle) * radius));
  }

  for (let s = 0; s < CANOPY_SEGMENTS; s += 1) {
    const next = (s + 1) % CANOPY_SEGMENTS;
    // Skirt of the cone (wound so the outward face points away from the axis).
    faces.push({ verts: [ring[s], apex, ring[next]], group: "canopy" });
    // Underside cap so the tier reads as solid from below.
    faces.push({ verts: [ring[s], ring[next], addVertex(0, baseY, 0)], group: "canopy" });
  }
}

buildTrunk();
for (const tier of CANOPY_TIERS) {
  buildCanopyTier(tier.baseY, tier.radius, tier.height);
}

const objLines = [
  "# Thunder Tank low-poly urban tree",
  "# Generated by scripts/generate-tree-model.mjs — do not edit by hand.",
  "mtllib tree.mtl",
  "o Tree",
];

for (const [x, y, z] of positions) {
  objLines.push(`v ${x.toFixed(5)} ${y.toFixed(5)} ${z.toFixed(5)}`);
}

let currentGroup = "";
for (const face of faces) {
  if (face.group !== currentGroup) {
    objLines.push(`usemtl ${face.group}`);
    currentGroup = face.group;
  }
  objLines.push(`f ${face.verts.join(" ")}`);
}

const mtlLines = [
  "# Thunder Tank low-poly urban tree materials",
  "# Generated by scripts/generate-tree-model.mjs — do not edit by hand.",
  "newmtl trunk",
  "Kd 0.42 0.31 0.20",
  "Ka 0.10 0.07 0.05",
  "Ks 0.02 0.02 0.02",
  "Ns 8.0",
  "",
  "newmtl canopy",
  "Kd 0.24 0.52 0.28",
  "Ka 0.06 0.14 0.07",
  "Ks 0.03 0.05 0.03",
  "Ns 6.0",
];

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "tree.obj"), `${objLines.join("\n")}\n`);
writeFileSync(resolve(outDir, "tree.mtl"), `${mtlLines.join("\n")}\n`);

console.log(`Wrote ${positions.length} vertices / ${faces.length} faces to ${outDir}`);
