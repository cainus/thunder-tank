// Generates the low-poly crate model (Wavefront .obj + .mtl) that the in-game 3D
// renderer loads for the square "crate" obstacles. Mirrors the tree generator
// (scripts/generate-tree-model.mjs): keeping the geometry in a small,
// deterministic generator lets us regenerate/tweak the model without committing
// an opaque binary asset. Run with `node scripts/generate-crate-model.mjs`.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../public/assets/models");

// The model is authored around a 1-unit "footprint": the crate sits on the
// ground plane (y = 0) centred on the origin and spans a 1x1 footprint so the
// renderer can scale it to any world size uniformly (see CRATE_WORLD_SCALE).
const HALF = 0.5; // half the footprint width/depth
const HEIGHT = 0.72; // crate stands a little shorter than it is wide
// Width of the frame border stamped around each face; the inner region is a
// coplanar recessed-looking "panel" in a lighter material so the box reads as a
// slatted crate rather than a plain cube. Frame and panel are coplanar (no
// overlap, no gap), so there is no z-fighting and normals stay clean.
const BORDER = 0.1;

const positions = [];
const faces = []; // { verts: [i, j, k], group }

function addVertex(x, y, z) {
  positions.push([x, y, z]);
  return positions.length; // .obj indices are 1-based
}

function add(a, b) {
  return [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
}

function scale(v, s) {
  return [v[0] * s, v[1] * s, v[2] * s];
}

// Emits a quad as two triangles. Corners must be given counter-clockwise as seen
// from outside the face so computeVertexNormals() (run by the loader) points the
// normal outward.
function addQuad(a, b, c, d, group) {
  const ia = addVertex(...a);
  const ib = addVertex(...b);
  const ic = addVertex(...c);
  const id = addVertex(...d);
  faces.push({ verts: [ia, ib, ic], group });
  faces.push({ verts: [ia, ic, id], group });
}

// Builds one framed face: a picture-frame border (frame material) around a
// coplanar inner panel (panel material). `origin` is the face centre, `u`/`v`
// are the in-plane right/up unit axes, and `halfU`/`halfV` the face half-extents.
function addFramedFace(origin, u, v, halfU, halfV) {
  const corner = (su, sv, inset) =>
    add(add(origin, scale(u, su * (halfU - inset))), scale(v, sv * (halfV - inset)));

  const outerBL = corner(-1, -1, 0);
  const outerBR = corner(1, -1, 0);
  const outerTR = corner(1, 1, 0);
  const outerTL = corner(-1, 1, 0);

  const innerBL = corner(-1, -1, BORDER);
  const innerBR = corner(1, -1, BORDER);
  const innerTR = corner(1, 1, BORDER);
  const innerTL = corner(-1, 1, BORDER);

  // Frame border, as four strips winding CCW from outside.
  addQuad(outerBL, outerBR, innerBR, innerBL, "crateFrame");
  addQuad(outerBR, outerTR, innerTR, innerBR, "crateFrame");
  addQuad(outerTR, outerTL, innerTL, innerTR, "crateFrame");
  addQuad(outerTL, outerBL, innerBL, innerTL, "crateFrame");

  // Inner panel.
  addQuad(innerBL, innerBR, innerTR, innerTL, "cratePanel");
}

// Builds one flat, single-material quad (used for the rarely-seen underside).
function addPlainFace(origin, u, v, halfU, halfV, group) {
  const corner = (su, sv) => add(add(origin, scale(u, su * halfU)), scale(v, sv * halfV));
  addQuad(corner(-1, -1), corner(1, -1), corner(1, 1), corner(-1, 1), group);
}

const midY = HEIGHT / 2;
const halfV = HEIGHT / 2;

// Four sides + the top get a framed panel; the top is the most visible face
// under the tilted top-down camera. `u`/`v` are wound so each face's outward
// normal points away from the box centre.
addFramedFace([HALF, midY, 0], [0, 0, -1], [0, 1, 0], HALF, halfV); // +X
addFramedFace([-HALF, midY, 0], [0, 0, 1], [0, 1, 0], HALF, halfV); // -X
addFramedFace([0, midY, HALF], [1, 0, 0], [0, 1, 0], HALF, halfV); // +Z
addFramedFace([0, midY, -HALF], [-1, 0, 0], [0, 1, 0], HALF, halfV); // -Z
addFramedFace([0, HEIGHT, 0], [1, 0, 0], [0, 0, -1], HALF, HALF); // top (+Y)

// Underside, wound CCW as seen from below so its normal points down (-Y).
addPlainFace([0, 0, 0], [1, 0, 0], [0, 0, 1], HALF, HALF, "crateFrame");

const objLines = [
  "# Thunder Tank low-poly crate obstacle",
  "# Generated by scripts/generate-crate-model.mjs — do not edit by hand.",
  "mtllib crate.mtl",
  "o Crate",
];

for (const [x, y, z] of positions) {
  objLines.push(`v ${x.toFixed(5)} ${y.toFixed(5)} ${z.toFixed(5)}`);
}

let currentGroup = "";
for (const face of faces) {
  if (face.group !== currentGroup) {
    objLines.push(`usemtl ${face.group}`);
    currentGroup = face.group;
  }
  objLines.push(`f ${face.verts.join(" ")}`);
}

const mtlLines = [
  "# Thunder Tank low-poly crate obstacle materials",
  "# Generated by scripts/generate-crate-model.mjs — do not edit by hand.",
  // Steel-grey palette echoing the flat crateMetal sprite it replaces, and
  // legible on both the daytime road and the darker night maps.
  "newmtl crateFrame",
  "Kd 0.32 0.35 0.40",
  "Ka 0.08 0.09 0.10",
  "Ks 0.06 0.06 0.07",
  "Ns 12.0",
  "",
  "newmtl cratePanel",
  "Kd 0.52 0.56 0.62",
  "Ka 0.13 0.14 0.16",
  "Ks 0.05 0.05 0.06",
  "Ns 10.0",
];

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "crate.obj"), `${objLines.join("\n")}\n`);
writeFileSync(resolve(outDir, "crate.mtl"), `${mtlLines.join("\n")}\n`);

console.log(`Wrote ${positions.length} vertices / ${faces.length} faces to ${outDir}`);
